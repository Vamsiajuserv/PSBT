const LangCtx = createContext(null)
const KEY = 'psbt_lang'

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => (typeof localStorage !== 'undefined' && localStorage.getItem(KEY)) || 'en')
  const [cache, setCache] = useState({})
  const pending = useRef(new Set())
  const timer = useRef(null)

  const setLang = useCallback((l) => {
    setLangState(l)
    try { localStorage.setItem(KEY, l) } catch { /* ignore */ }
  }, [])

  // First visit (no saved choice) → follow the temple's configured Default
  // Language once the site content loads. A user's own pick is remembered and wins.
  const siteDefault = useSiteContext()?.site?.temple?.defaultLanguage
  useEffect(() => {
    if (typeof localStorage !== 'undefined' && localStorage.getItem(KEY)) return
    if (siteDefault === 'Telugu' || siteDefault === 'te') setLangState('te')
  }, [siteDefault])
  const toggle = useCallback(() => setLang(lang === 'en' ? 'te' : 'en'), [lang, setLang])

  const flush = useCallback(() => {
    const texts = [...pending.current]
    pending.current = new Set()
    if (!texts.length) return
    TranslateAPI.translate(texts, 'te').then((res) => {
      const map = res?.translations || {}
      const add = {}
      for (const [k, v] of Object.entries(map)) if (v && v !== k) add[k] = v
      if (Object.keys(add).length) setCache((c) => ({ ...c, ...add }))
    }).catch(() => { /* offline → stay English */ })
  }, [])

  const t = useCallback((text) => {
    if (lang === 'en' || text == null || text === '') return text
    const s = String(text)
    if (/[\u0C00-\u0C7F]/.test(s)) return s   // already Telugu — nothing to do
    const local = UI_TE[s] || glossaryTe(s)
    if (local) return local
    // Suffix-tolerant: "Collection Date *" / "Amount:" hit the base entry.
    const dm = s.match(/^(.*?)([\s:*…]+)$/)
    if (dm) {
      const base = UI_TE[dm[1].trim()] || glossaryTe(dm[1].trim())
      if (base) return base + dm[2]
    }
    // Leading count: "3-day festival pooja", "2 plans". The number is data, so
    // translate the phrase and keep the digits where they are.
    const nm = s.match(/^(\d+[-\s]?)(\D.*)$/)
    if (nm) {
      const base = UI_TE[nm[2]] || glossaryTe(nm[2])
      if (base) return nm[1] + base
    }
    // Audit details are "<Verb> <Entity>" — Create Booking, Update Devotee.
    // Composing them covers every verb/entity pair without an entry each.
    const am = s.match(/^(Create|Update|Delete|Denied|View|Export) (.+)$/)
    if (am) {
      const verb = UI_TE[am[1]], ent = UI_TE[am[2]] || glossaryTe(am[2])
      if (verb && ent) return `${ent} ${verb}`
    }
    // Composed content: "<Pooja name> — booked at the counter; …". Resolving
    // each half means one entry covers every pooja in the master, including
    // ones staff add later, instead of one entry per pooja.
    const parts = s.split(' — ')
    if (parts.length === 2) {
      const head = UI_TE[parts[0]] || glossaryTe(parts[0])
      const tail = UI_TE[parts[1]] || glossaryTe(parts[1])
      if (head && tail) return `${head} — ${tail}`
    }
    if (cache[s]) return cache[s]
    if (!pending.current.has(s)) {
      pending.current.add(s)
      clearTimeout(timer.current)
      timer.current = setTimeout(flush, 250)
    }
    return text
  }, [lang, cache, flush])

  // Module-level handle so tr() (attribute props: placeholder/title) and <T>
  // work anywhere without threading the hook through every component.
  reg.lang = lang
  reg.t = t

  // key={lang} remounts the subtree on toggle, so even strings resolved via the
  // module-level tr() re-evaluate instantly in the new language.
  return (
    <LangCtx.Provider value={{ lang, setLang, toggle, t }}>
      <React.Fragment key={lang}>{children}</React.Fragment>
    </LangCtx.Provider>
  )
}

// ── Hook-free helpers (usable in any component, incl. ones without hooks) ──
const reg = { lang: 'en', t: (s) => s }

// Attribute-position translation (placeholder=, title=). Re-evaluates on the
// provider's key={lang} remount; dictionary hits are instant.
export function tr(text) { return reg.t(text) }

// Text-node translation: <T>Some sentence</T>. Subscribes to the context, so
// late-arriving dynamic translations (Azure cache) also re-render.
export function T({ children }) {
  const { t } = useLang()
  if (children == null) return null
  return t(typeof children === 'string' || typeof children === 'number' ? String(children) : String(children))
}

export function useLang() {
  return useContext(LangCtx) || { lang: 'en', setLang: () => {}, toggle: () => {}, t: (x) => x }
}

// Content served from the database carries its own Telugu twin — `nameTe`
// beside `name`, `descTe` beside `desc`. The twin is authoritative: a
// dictionary entry would go stale the moment staff edit the English. t() is
// the fallback for content that has no twin yet.
//
//   const te = useContentText()
//   <p>{te(festival, 'desc')}</p>
export function useContentText() {
  const { lang, t } = useLang()
  return useCallback((obj, field) => {
    const en = obj?.[field] || ''
    if (lang !== 'te' || !obj) return en
    return obj[`${field}Te`] || t(en)
  }, [lang, t])
}

// A person's name in the active language. Names are never machine-translated —
// only the Telugu spelling the person themselves gave, stored as `name_te`
// beside `name`. No twin on record means the name shows exactly as entered,
// which is the safe default: a wrong name on a receipt is worse than an
// English one.
//
//   personName(devotee, lang)   or   usePersonName()(devotee)
export function personName(person, lang) {
  if (!person) return ''
  const en = person.name || person.devotee_name || ''
  return lang === 'te' ? (person.name_te || person.nameTe || en) : en
}

export function usePersonName() {
  const { lang } = useLang()
  return useCallback((person) => personName(person, lang), [lang])
}

// The temple address in the active language — the single source for every place
// the public site prints it. Both halves come from Admin → Settings → Address
// Details, so editing the address there updates the site in both languages.
// Telugu order: the staff-written field wins (place names are proper nouns the
// engine gets wrong), then the usual t() chain, then the English text.
export function useTempleAddress() {
  const { lang, t } = useLang()
  const temple = useSiteContext()?.site?.temple
  const en = temple?.address || ''
  return lang === 'te' ? (temple?.addressTe || t(en)) : en
}
